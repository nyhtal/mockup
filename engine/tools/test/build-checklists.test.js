import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { checklistRules, buildChecklists } from "../build-checklists.js";

const BYLAW_A = `# 01 HTML

### R-HTML-01 One h1 per page
MUST. Every page has exactly one h1.
Why: Screen readers key off it.
Gate: consistency/single-h1

### R-HTML-02 Keyboard walkthrough
MUST. Every control is reachable with the keyboard.
Why: WCAG 2.1.1.
Gate: manual: checklists/pre-delivery.md

### R-HTML-03 Dates
SHOULD. Dates are time elements.
Why: Machines read them.
Gate: manual: checklists/new-page.md
`;
const BYLAW_B = `# 05 Colour

### R-COL-01 Contrast
MUST. Text reaches 4.5:1.
Why: WCAG 1.4.3.
Gate: manual: checklists/pre-delivery.md
`;

function fixture() {
  const root = mkdtempSync(path.join(tmpdir(), "checklists-"));
  mkdirSync(path.join(root, "bylaws"));
  mkdirSync(path.join(root, "preambles"));
  writeFileSync(path.join(root, "bylaws", "01-html.md"), BYLAW_A);
  writeFileSync(path.join(root, "bylaws", "05-color.md"), BYLAW_B);
  writeFileSync(path.join(root, "preambles", "pre-delivery.md"), "# Pre-delivery checklist\n\nRun the gates first.\n");
  return root;
}

test("checklistRules groups rules by the checklist their Gate line names, keeping bylaw file, level and the rule sentence", () => {
  const root = fixture();
  try {
    const rules = checklistRules(path.join(root, "bylaws"));
    assert.deepEqual(Object.keys(rules).sort(), ["new-page", "pre-delivery"]);
    assert.deepEqual(rules["pre-delivery"].map((r) => r.id), ["R-HTML-02", "R-COL-01"]);
    assert.deepEqual(rules["new-page"][0], { id: "R-HTML-03", title: "Dates", level: "SHOULD", text: "Dates are time elements.", file: "01-html.md" });
  } finally { rmSync(root, { recursive: true, force: true }); }
});

test("buildChecklists writes one file per checklist with the preamble above a per-bylaw list of checkbox items that cite the rule id", () => {
  const root = fixture();
  try {
    const out = path.join(root, "out");
    const written = buildChecklists({ bylawsDir: path.join(root, "bylaws"), preamblesDir: path.join(root, "preambles"), outDir: out });
    assert.deepEqual(written.sort(), ["new-page.md", "pre-delivery.md"]);
    const pre = readFileSync(path.join(out, "pre-delivery.md"), "utf8");
    assert.match(pre, /^# Pre-delivery checklist\n\nRun the gates first\./);
    assert.match(pre, /## Rules this checklist verifies/);
    assert.match(pre, /### 01 HTML[\s\S]*- \[ \] \*\*R-HTML-02\*\* Keyboard walkthrough — Every control is reachable with the keyboard\./);
    assert.match(pre, /### 05 Colour[\s\S]*- \[ \] \*\*R-COL-01\*\* Contrast/);
    assert.match(pre, /generated by `npm run checklists`/i);
    // A checklist without a preamble still gets a title.
    assert.match(readFileSync(path.join(out, "new-page.md"), "utf8"), /^# New page checklist/);
    assert.ok(!existsSync(path.join(out, "new-site.md")));
  } finally { rmSync(root, { recursive: true, force: true }); }
});
