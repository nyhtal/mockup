import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseRules } from "./gates/bylaws.js";

const HEADING = /^### (R-[A-Z0-9]+-\d{2}) (.+)$/;
const TITLES = { "new-site": "New site checklist", "new-page": "New page checklist", "new-component": "New component checklist", "new-locale": "New locale checklist", "pre-delivery": "Pre-delivery checklist" };

/** The rule sentence after "MUST." or "SHOULD." on the line that follows a rule heading. */
function ruleText(markdown, ruleId) {
  const lines = markdown.split(/\r?\n/);
  const i = lines.findIndex((l) => { const m = HEADING.exec(l); return m && m[1] === ruleId; });
  for (let j = i + 1; j < lines.length; j++) {
    const l = lines[j].trim();
    if (l) return l.replace(/^(MUST|SHOULD)\.\s*/, "");
  }
  return "";
}

/** Rules whose Gate line names a checklist, grouped by checklist name, in bylaw order (R-GATE-12). */
export function checklistRules(bylawsDir) {
  const out = {};
  for (const file of readdirSync(bylawsDir).filter((f) => f.endsWith(".md")).sort()) {
    const md = readFileSync(path.join(bylawsDir, file), "utf8");
    for (const r of parseRules(md)) {
      const m = /^manual: checklists\/([\w-]+)\.md$/.exec(r.gate || "");
      if (!m) continue;
      (out[m[1]] ||= []).push({ id: r.id, title: r.title, level: r.level, text: ruleText(md, r.id), file });
    }
  }
  return out;
}

const bylawTitle = (dir, file) => (/^# (.+)$/m.exec(readFileSync(path.join(dir, file), "utf8"))?.[1] || file);

/** Write engine/checklists/<name>.md: the hand-written preamble, then every rule the checklist verifies, grouped by bylaw. */
export function buildChecklists({ bylawsDir = path.join("engine", "bylaws"), preamblesDir = path.join("engine", "checklists", "_preambles"), outDir = path.join("engine", "checklists") } = {}) {
  const rules = checklistRules(bylawsDir);
  mkdirSync(outDir, { recursive: true });
  const written = [];
  for (const [name, list] of Object.entries(rules)) {
    const preambleFile = path.join(preamblesDir, `${name}.md`);
    const preamble = existsSync(preambleFile) ? readFileSync(preambleFile, "utf8").trim() : `# ${TITLES[name] || `${name} checklist`}`;
    const byFile = new Map();
    for (const r of list) { if (!byFile.has(r.file)) byFile.set(r.file, []); byFile.get(r.file).push(r); }
    const lines = [preamble, "", "## Rules this checklist verifies", "", `Generated by \`npm run checklists\` from every rule whose \`Gate:\` line names \`checklists/${name}.md\`; edit the bylaws or the preamble in \`_preambles/\`, not this list. Tick each item or record the override in the site's \`DECISIONS.md\` (R-PREC-02; tier-1 rules cannot be overridden).`, ""];
    for (const [file, items] of byFile) {
      lines.push(`### ${bylawTitle(bylawsDir, file)}`, "");
      for (const r of items) lines.push(`- [ ] **${r.id}** ${r.title} — ${r.text}${r.level === "SHOULD" ? " *(SHOULD)*" : ""}`);
      lines.push("");
    }
    writeFileSync(path.join(outDir, `${name}.md`), lines.join("\n").trimEnd() + "\n");
    written.push(`${name}.md`);
  }
  return written;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const f of buildChecklists()) console.log(`wrote engine/checklists/${f}`);
}
